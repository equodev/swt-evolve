import 'dart:io';
import 'package:flutter/material.dart';
import 'package:swtflutter/src/theme/named_theme.dart';
import 'package:swtflutter/src/theme/theme_extensions/canvas_theme_extension.dart';
import './java_value_class.dart';
import './measure.dart' show defaultSizeOutputDir;

/// Generates dev/equo/swt/size/CanvasTheme.java from the dark theme the default named theme draws:
/// its CanvasThemeExtension's backgroundColor, the ground of a genuinely Dart-rendered Canvas, and
/// foregroundColor, the foreground meant to be legible on it.
///
/// Unlike the other measure_*.dart scripts, there's no widget to render or TextStyle to measure —
/// a Canvas draws no text of its own — so this reads the theme directly instead of going through
/// WidgetMeasurer/MeasurementApp, and exits immediately after writing the file.
void main() {
  WidgetsFlutterBinding.ensureInitialized();
  writeCanvasThemeFile();
  exit(0);
}

int _toByte(double component) => (component * 255.0).round().clamp(0, 255);

void writeCanvasThemeFile({String outputDir = defaultSizeOutputDir}) {
  final canvasTheme = namedThemeFor(kDefaultThemeName)
      .build(null, dark: true)
      .extension<CanvasThemeExtension>()!;
  final surface = canvasTheme.backgroundColor;
  final red = _toByte(surface.r);
  final green = _toByte(surface.g);
  final blue = _toByte(surface.b);
  final onSurface = canvasTheme.foregroundColor;
  final onRed = _toByte(onSurface.r);
  final onGreen = _toByte(onSurface.g);
  final onBlue = _toByte(onSurface.b);

  final buffer = StringBuffer();
  buffer.writeln('package dev.equo.swt.size;');
  buffer.writeln();
  buffer.writeln('/**');
  buffer.writeln(
    ' * Mirrors the {@code CanvasThemeExtension} background and foreground of the default named',
  );
  buffer.writeln(
    ' * theme\'s dark variant ({@code flutter-lib/lib/src/theme/named_theme.dart}): the colors a',
  );
  buffer.writeln(
    ' * genuinely Dart-rendered Canvas is drawn in.',
  );
  buffer.writeln(' *');
  buffer.writeln(
    ' * <p>Generated by {@code flutter-lib/tool/measure_canvas.dart} — unlike {@link ButtonTheme}',
  );
  buffer.writeln(
    ' * and its siblings, which measure live {@code TextStyle} font metrics, this reads the',
  );
  buffer.writeln(
    ' * theme directly (a Canvas draws no text of its own to measure).',
  );
  buffer.writeln(' *');
  buffer.writeln(
    ' * <p>There is no live Dart-to-Java channel a synchronous Java call like',
  );
  buffer.writeln(
    ' * {@code Display.getSystemColor()} can use to read this at call time — colors only flow',
  );
  buffer.writeln(
    ' * Java-config to Dart-theme, never the other way, and Java may run before Flutter has even',
  );
  buffer.writeln(
    ' * connected. So the value is mirrored here as a literal, regenerated by re-running this script',
  );
  buffer.writeln(
    ' * whenever the default theme\'s dark colors change.',
  );
  buffer.writeln(' *');
  buffer.writeln(
    ' * <p>The two are a pair: a system foreground color must be read from the same scheme as the',
  );
  buffer.writeln(
    ' * background it is drawn on, or an application that sets neither inherits one of each theme.',
  );
  buffer.writeln(' */');
  buffer.write(
    javaValueClass('CanvasTheme', const [
      ('int', 'red'),
      ('int', 'green'),
      ('int', 'blue'),
    ]),
  );
  buffer.writeln('    public static CanvasTheme getDarkSurface() {');
  buffer.writeln('        return new CanvasTheme($red, $green, $blue);');
  buffer.writeln('    }');
  buffer.writeln();
  buffer.writeln('    public static CanvasTheme getDarkOnSurface() {');
  buffer.writeln('        return new CanvasTheme($onRed, $onGreen, $onBlue);');
  buffer.writeln('    }');
  buffer.writeln('}');

  final file = File(
    '$outputDir/CanvasTheme.java',
  );
  file.writeAsStringSync(buffer.toString());
  print('Generated: ${file.path}');
}
